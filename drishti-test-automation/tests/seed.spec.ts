/**
 * Seed test for the Playwright generator agent.
 *
 * The generator mirrors whatever this file does, so the seed is the single
 * most effective place to teach it the house style. It therefore imports the
 * framework fixtures rather than `@playwright/test`, and resolves an element
 * by key instead of by selector.
 *
 * Do not add real assertions here — this file exists to establish context and
 * conventions, and `tests/e2e/**` is where real suites live.
 */
import { test, expect } from '../src/fixtures/index.js';

test.describe('Test group', () => {
  test('seed', async ({ ui }) => {
    // Conventions for generated tests:
    //   1. Navigate through `ui`, using a path relative to `baseURL`.
    //   2. Never write a selector inline. Declare the element in a
    //      `locators/<namespace>.locators.yml` file and refer to it by key.
    //   3. Assert with the web-first `ui.expect(key)` helpers.
    //   4. Wrap logical phases in `test.step()`.
    await ui.goto('#/');

    await test.step('example: act on a declared element', async () => {
      await ui.fill('todo.newTodoInput', 'generated by an agent');
      await ui.press('todo.newTodoInput', 'Enter');
    });

    await ui.expect('todo.todoItems').toHaveCount(1);

    // `expect` is re-exported for assertions that are not element-scoped.
    expect(await ui.textOf('todo.counter')).toContain('1 item');

    // generate code here.
  });
});

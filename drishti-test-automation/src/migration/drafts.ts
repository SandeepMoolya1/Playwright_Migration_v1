/** Members of BasePage a draft method must not shadow. */
function baseMembers(rootDir: string): Set<string> {
  const text = fs.readFileSync(path.join(rootDir, 'src', 'pages', 'base.page.ts'), 'utf8');
  const names = [...text.matchAll(/^\s*(?:protected|public|private)?\s*(?:readonly\s+)?(?:async\s+)?(?:get\s+)?(\w+)\s*[(:]/gm)].map((m) => m[1]!);
  return new Set([...names, 'ui', 'namespace', 'constructor']);
}

function accessorOf(method: JavaMethod, elements: Set<string>): { returnType: string; expr: string } | undefined {
  const body = method.body.replace(/\s+/g, ' ').trim();
  const one = (names: string, extra = ''): RegExpExecArray | null =>
    new RegExp(`^return\\s+(?:this\\s*\\.\\s*)?(?:${names})\\s*\\(\\s*(\\w+)\\s*${extra}\\)\\s*;?$`).exec(body);
  let m = one('getTextOnElement|safeGetText');
  if (m && elements.has(m[1]!)) return { returnType: 'string', expr: `this.textOf('${m[1]}')` };
  m = one('isWebElementDisplayed|isElementVisible|isElementPresent|isElementPresentImmediately');
  if (m && elements.has(m[1]!)) return { returnType: 'boolean', expr: `this.isVisible('${m[1]}')` };
  m = one('isWebElementEnabled|isElementClickable');
  if (m && elements.has(m[1]!)) return { returnType: 'boolean', expr: `(await this.locator('${m[1]}')).isEnabled()` };
  m = one('sizeOfWebElements|getElementCount|safeGetSize');
  if (m && elements.has(m[1]!)) return { returnType: 'number', expr: `this.countOf('${m[1]}')` };
  m = one('getAttribute', ',\\s*"([^"]*)"\\s*');
  if (m && elements.has(m[1]!)) return { returnType: 'string | null', expr: `(await this.locator('${m[1]}')).getAttribute('${m[2]}')` };
  m = /^return\s+(\w+)\s*\.\s*getText\s*\(\s*\)\s*;?$/.exec(body);
  if (m && elements.has(m[1]!)) return { returnType: 'string', expr: `this.textOf('${m[1]}')` };
  m = /^return\s+(\w+)\s*\.\s*isDisplayed\s*\(\s*\)\s*;?$/.exec(body);
  if (m && elements.has(m[1]!)) return { returnType: 'boolean', expr: `this.isVisible('${m[1]}')` };
  return undefined;
}

/** Kinds a page-object method can contain and still be called clean. */
const CLEAN_KINDS = new Set<MigratedStep['kind']>([
  'click', 'doubleClick', 'fill', 'type', 'clear', 'press', 'check', 'uncheck', 'selectOption', 'hover',
  'expectVisible', 'expectHidden', 'expectText', 'expectContainsText', 'expectValue', 'expectEnabled',
  'expectDisabled', 'expectChecked', 'expectCount', 'comment',
]);

export interface PageMethodInfo {
  name: string;
  params: Array<{ name: string; type: string }>;
  returnType: string;
  clean: boolean;
}

function renderPageMethod(
  method: JavaMethod,
  tsName: string,
  namespace: string,
  elements: Set<string>,
  overloads: number,
): { code: string; info: PageMethodInfo } {
  const doc = `  /** Selenium: ${method.name}(${method.params.map((p) => `${p.type} ${p.name}`).join(', ')}) — line ${method.line}. */`;

  if (overloads > 1) {
    const info = { name: tsName, params: [], returnType: 'unknown', clean: false };
    return {
      code: `${doc}\n  // TODO(migration): ${overloads} Java overloads share this name — split into distinct methods.\n  async ${tsName}(..._args: unknown[]): Promise<unknown> {\n    throw new Error(${q(`TODO(migration): ${namespace}.${tsName}() is not migrated yet`)});\n  }`,
      info,
    };
  }

  const params = method.params.map((p) => ({ name: p.name, type: tsType(p.type) }));
  const sig = params.map((p) => `${p.name}: ${p.type === 'void' ? 'unknown' : p.type}`).join(', ');
  const names = new Set(params.map((p) => p.name));
  const ret = tsType(method.returnType);

  const accessor = accessorOf(method, elements);
  if (accessor) {
    return {
      code: `${doc}\n  async ${tsName}(${sig}): Promise<${accessor.returnType}> {\n    return ${accessor.expr};\n  }`,
      info: { name: tsName, params, returnType: accessor.returnType, clean: true },
    };
  }

  const lines: string[] = [];
  let clean = ret === 'void';
  for (const s of method.steps) {
    const ok =
      CLEAN_KINDS.has(s.kind) &&
      (s.kind === 'comment' || (s.target !== undefined && elements.has(s.target))) &&
      s.args.every((a) => isSafeArg(a, names));
    if (!ok) {
      clean = false;
      lines.push(`    // TODO(migration): ${s.note ?? `not translated (${s.kind})`}`, `    //   was: ${s.source.replace(/\s+/g, ' ').slice(0, 200)}`);
      continue;
    }
    // Full `ns.key` keys throughout: BasePage.key() passes dotted keys through.
    lines.push(...renderStep(s, namespace, '    ').map((l) => l.replace(/\bui\./g, 'this.ui.')));
  }
  if (!method.steps.length && ret === 'void' && !/^\s*$/.test(method.body)) {
    clean = false;
    lines.push('    // TODO(migration): no statement of this method could be read.');
  }
  if (!clean) {
    if (ret !== 'void') lines.push(`    // TODO(migration): returned ${method.returnType} in Java — return it from here.`);
    lines.push(`    throw new Error(${q(`TODO(migration): ${namespace}.${tsName}() is not migrated yet`)});`);
  }
  const promise = clean ? 'void' : ret === 'void' ? 'void' : ret;
  return {
    code: `${doc}\n  async ${tsName}(${sig}): Promise<${promise}> {\n${lines.join('\n') || '    // (empty in Java)'}\n  }`,
    info: { name: tsName, params, returnType: promise, clean },
  };
}

function emitPageObject(
  cls: JavaClass,
  namespace: string,
  reserved: Set<string>,
  opts: DraftOptions,
  summary: DraftSummary,
  record: DraftSummary['pages'][number],
): { className: string; file: string; methods: Map<string, PageMethodInfo> } {
  const className = `${pascal(namespace)}Page`;
  const elements = new Set(cls.fields.map((f) => f.name));
  const candidates = cls.methods.filter((m) => m.name !== cls.name && m.returnType !== 'By');
  const counts = new Map<string, number>();
  for (const m of candidates) counts.set(m.name, (counts.get(m.name) ?? 0) + 1);

  const methods = new Map<string, PageMethodInfo>();
  const blocks: string[] = [];
  for (const m of candidates) {
    if (methods.has(m.name)) continue;
    const tsName = reserved.has(m.name) ? `${m.name}Action` : m.name;
    const { code, info } = renderPageMethod(m, tsName, namespace, elements, counts.get(m.name)!);
    methods.set(m.name, info);
    blocks.push(code);
    if (info.clean) record.cleanMethods++;
    else record.todoMethods++;
  }

  const file = path.join(opts.rootDir, 'src', 'pages', 'drafts', `${kebab(namespace)}.page.ts`);
  const code = `/**
 * ${DRAFT_MARKER} — generated by \`npm run migrate:drafts\`; regenerated on every run.
 * Source: ${opts.sourceLabel} — ${cls.relativeFile}.
 *
 * Locators: locators/${namespace}.locators.yml. A method that did not translate
 * cleanly throws, so nothing can pass by silently skipping it. To curate, move
 * this file to src/pages/, resolve every TODO(migration) and verify it on STG.
 */
import { BasePage } from '../base.page.js';
import type { SmartPage } from '../../fixtures/smart-page.js';

export class ${className} extends BasePage {
  constructor(ui: SmartPage) {
    super(ui, '${namespace}');
  }
${blocks.length ? `\n${blocks.join('\n\n')}\n` : ''}}
`;
  writeFile(file, code, opts, summary);
  record.page = path.relative(opts.rootDir, file);
  return { className, file, methods };
}


/** Steps every KSP scenario repeats, and what they are in this framework. */
const COMMON_STEPS: Array<{ re: RegExp; code?: (role: string | undefined) => string; note: string }> = [
  {
    re: /^User open the Application$/,
    code: () => 'await login.openApplication(startPath);',
    note: 'opens the start page',
  },
  {
    re: /^User enter the login Credentials for '([^']*)' user$/,
    note: 'signed in once per role by the auth setup project (storage state)',
  },
  { re: /^User click on the login button$/, note: 'signed in by the auth setup project' },
  {
    re: /^User is logged in successfully$/,
    code: () => 'await login.expectLoggedIn();',
    note: 'every test still asserts the session is live',
  },
];

interface PageRef {
  className: string;
  importPath: string;
  methods: Map<string, PageMethodInfo>;
}

interface SpecContext {
  definitions: StepDefinition[];
  /** step-definition class → its page-object field name → Java page class. */
  glueVars: Map<string, Map<string, string>>;
  pages: Map<string, PageRef>;
  used: Set<string>;
  unbound: Map<string, number>;
}

function renderGherkinStep(step: GherkinStep, ctx: SpecContext, role: string | undefined): { lines: string[]; todo: boolean; unbound: boolean } {
  const title = `${step.writtenKeyword} ${step.text}`;
  const common = COMMON_STEPS.find((c) => c.re.test(step.text));
  if (common) {
    if (!common.code) return { lines: [`      // ${title} — ${common.note}`], todo: false, unbound: false };
    return {
      lines: [`      await test.step(${q(title)}, async () => {`, `        ${common.code(role)}`, '      });'],
      todo: false,
      unbound: false,
    };
  }

  const match = matchStep(step, ctx.definitions);
  if (!match) {
    ctx.unbound.set(step.text, (ctx.unbound.get(step.text) ?? 0) + 1);
    return {
      lines: [
        `      await test.step(${q(title)}, async () => {`,
        '        // TODO(migration): no step definition matched this Gherkin step.',
        `        throw new Error(${q(`TODO(migration): unbound step: ${title}`)});`,
        '      });',
      ],
      todo: true,
      unbound: true,
    };
  }

  const def = match.definition;
  const vars = ctx.glueVars.get(def.className) ?? new Map<string, string>();
  const body: string[] = [`        // ${def.className}.${def.method.name}() — ${def.file}:${def.line}`];
  let todo = false;
  const bind = (a: string): string => {
    const bare = a.trim();
    return match.bindings.get(bare) ?? match.bindings.get(/^'(.*)'$/.exec(bare)?.[1] ?? '') ?? a;
  };
  const noNames = new Set<string>();

  for (const s of def.method.steps) {
    const javaClass = s.target ? vars.get(s.target) : undefined;
    const page = javaClass ? ctx.pages.get(javaClass) : undefined;

    if ((s.kind === 'callMethod' || s.kind === 'expectMethodResult') && page) {
      const [method, ...rest] = s.args;
      const info = page.methods.get(method!);
      const varName = camel(page.className);
      if (info && s.kind === 'callMethod') {
        const args = rest.map(bind);
        if (args.length === info.params.length && args.every((a) => isSafeArg(a, noNames))) {
          ctx.used.add(javaClass!);
          body.push(`        await ${varName}.${info.name}(${args.map((a, i) => coerce(a, info.params[i]!.type)).join(', ')});`);
          continue;
        }
      }
      if (info && s.kind === 'expectMethodResult' && info.params.length === 0) {
        const matcher = /^(\w+)\(([\s\S]*)\)$/.exec(rest[0]!);
        const inner = matcher ? bind(matcher[2]!) : undefined;
        if (matcher && inner !== undefined && (inner === '' || isSafeArg(inner, noNames))) {
          ctx.used.add(javaClass!);
          body.push(`        expect(await ${varName}.${info.name}()).${matcher[1]}(${inner});`);
          continue;
        }
      }
    }
    if (s.kind === 'comment') {
      body.push(...renderStep(s, '', '        '));
      continue;
    }
    todo = true;
    body.push(`        // TODO(migration): ${s.note ?? `not translated (${s.kind})`}`, `        //   was: ${s.source.replace(/\s+/g, ' ').slice(0, 200)}`);
  }
  if (!def.method.steps.length) {
    todo = true;
    body.push('        // TODO(migration): the step definition had no translatable statements.');
  }
  if (step.dataTable?.length) {
    todo = true;
    body.push('        // TODO(migration): this step received a data table:', ...step.dataTable.map((r) => `        //   | ${r.join(' | ')} |`));
  }
  if (todo) body.push(`        throw new Error(${q(`TODO(migration): ${title}`)});`);
  return { lines: [`      await test.step(${q(title)}, async () => {`, ...body, '      });'], todo, unbound: false };
}

function emitFeatureDraft(
  feature: GherkinFeature,
  ctx: SpecContext,
  curated: Curated,
  opts: DraftOptions,
  summary: DraftSummary,
): DraftSummary['features'][number] {
  const base = path.basename(feature.relativeFile, '.feature');
  const prefix = /[\\/]E2E_WorkFlows[\\/]/i.test(feature.relativeFile) ? 'e2e-' : '';
  const specName = `${prefix}${kebab(base)}.spec.ts`;
  const record: DraftSummary['features'][number] = {
    file: feature.relativeFile,
    scenarios: 0,
    drafted: 0,
    alreadyMigrated: [],
    todoSteps: 0,
    unboundSteps: 0,
  };

  ctx.used = new Set();
  const titles = new Set<string>();
  const blocks: string[] = [];

  const rows: Array<{ name: string; tags: string[]; steps: GherkinStep[]; values?: Record<string, string> }> = [];
  for (const sc of feature.scenarios) {
    if (!sc.isOutline) {
      rows.push({ name: sc.name, tags: sc.tags, steps: sc.steps });
      continue;
    }
    for (const ex of sc.examples) {
      for (const row of ex.rows) {
        rows.push({
          name: substituteOutline(sc.name, ex.headers, row),
          tags: [...sc.tags, ...ex.tags],
          steps: sc.steps.map((s) => ({ ...s, text: substituteOutline(s.text, ex.headers, row) })),
          values: Object.fromEntries(ex.headers.map((h, i) => [h, row[i] ?? ''])),
        });
      }
    }
  }

  for (const r of rows) {
    record.scenarios++;
    const tags = [...new Set([...feature.tags, ...r.tags])];
    const id =
      r.values?.TestCaseID || r.values?.['Test Case ID'] || r.values?.TestCaseId ||
      tags.find((t) => /^[A-Z]{2,6}[-_]\d+$/.test(t));
    if (id && curated.ids.has(id)) {
      record.alreadyMigrated.push(`${id} (${curated.ids.get(id)})`);
      continue;
    }
    const role =
      r.values?.User ??
      tags.find((t) => opts.knownRoles.includes(t)) ??
      /login Credentials for '([^']*)' user/.exec(r.steps.map((s) => s.text).join('\n'))?.[1];
    if (role && !opts.knownRoles.includes(role)) summary.missingRoles.set(role, (summary.missingRoles.get(role) ?? 0) + 1);
    const allTags = [...new Set([...tags, ...(id ? [id] : []), ...(role ? [role] : [])])]
      .filter((t) => /^[\w.:-]+$/.test(t))
      .map((t) => `@${t}`);

    let title = r.name.replace(/^\s*['"]([^'"]+)['"]\s*:\s*/, '$1: ').replace(/\s+/g, ' ').trim();
    if (id && !title.includes(id)) title = `${id}: ${title}`;
    for (let n = 2; titles.has(title); n++) title = `${title.replace(/ \[#\d+\]$/, '')} [#${n}]`;
    titles.add(title);

    const steps = r.steps.map((s) => renderGherkinStep(s, ctx, role));
    record.todoSteps += steps.filter((s) => s.todo).length;
    record.unboundSteps += steps.filter((s) => s.unbound).length;
    record.drafted++;
    blocks.push(
      `  test.fixme(${q(title)}, { tag: ${JSON.stringify(allTags)} }, async () => {\n${steps.flatMap((s) => s.lines).join('\n')}\n  });`,
    );
  }

  if (!record.drafted) return record;

  const background = feature.background.map((s) => renderGherkinStep(s, ctx, undefined));
  const used = [...ctx.used].map((j) => ctx.pages.get(j)!).filter(Boolean);
  const alias = (cls: string): string => (cls === 'LoginPage' ? 'LoginDraftPage' : cls);
  const imports = [
    "import { test, expect } from '../../src/fixtures/index.js';",
    "import { LoginPage } from '../../src/pages/login.page.js';",
    ...used.map((p) =>
      p.className === 'LoginPage'
        ? `import { LoginPage as LoginDraftPage } from '${p.importPath}';`
        : `import { ${p.className} } from '${p.importPath}';`,
    ),
  ];
  const decls = ['  let startPath = \'\';', '  let login: LoginPage;', ...used.map((p) => `  let ${camel(p.className)}: ${alias(p.className)};`)];
  const construct = ['    login = new LoginPage(ui);', ...used.map((p) => `    ${camel(p.className)} = new ${alias(p.className)}(ui);`)];
  const backgroundLines = background.flatMap((b) => b.lines.map((l) => l.slice(2)));
  const featureTag = feature.tags.find((t) => /^[\w.:-]+$/.test(t));

  const code = `/**
 * ${DRAFT_MARKER} — generated by \`npm run migrate:drafts\`; regenerated on every run.
 * Source: ${opts.sourceLabel} — ${feature.relativeFile}
 * Feature: ${feature.name}
 *
 * Every test is \`test.fixme\`: listed and reported, never executed. To migrate a
 * scenario, follow .claude/skills/aiqa-ksp-migration (move it into a curated
 * spec under tests/e2e/, resolve every TODO(migration), run it on STG). Once
 * its ID is in tests/e2e/, the next regeneration drops it from here.
 */
${imports.join('\n')}

test.describe(${q(feature.name)}, ${featureTag ? `{ tag: '@${featureTag}' }, ` : ''}() => {
${decls.join('\n')}

  test.beforeEach(async ({ ui, env }) => {
    startPath = env.startPath ?? '';
${construct.join('\n')}
${backgroundLines.join('\n')}
  });

${blocks.join('\n\n')}
});
`;
  const file = path.join(opts.rootDir, 'tests', 'drafts', specName);
  writeFile(file, code, opts, summary);
  record.spec = path.relative(opts.rootDir, file);
  return record;
}


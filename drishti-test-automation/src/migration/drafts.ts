export function generateDrafts(opts: DraftOptions): DraftSummary {
  const inventory = analyse(opts.input);
  const curated = readCurated(opts.rootDir);
  const reserved = baseMembers(opts.rootDir);
  const summary: DraftSummary = { features: [], pages: [], missingRoles: new Map(), unbound: new Map(), written: [] };

  clearDrafts(path.join(opts.rootDir, 'tests', 'drafts'), '.spec.ts', opts);
  clearDrafts(path.join(opts.rootDir, 'src', 'pages', 'drafts'), '.page.ts', opts);
  clearDrafts(path.join(opts.rootDir, 'locators'), '.locators.yml', opts);

  const pages = new Map<string, PageRef>();
  const pageClasses = inventory.classes
    .filter((c) => c.kind === 'page' || (c.kind !== 'steps' && /[\\/]pages[\\/]/.test(c.file)))
    .filter((c) => c.name !== 'BasePage')
    .sort((a, b) => a.name.localeCompare(b.name));

  const naturalNamespaces = new Map(pageClasses.map((cls) => [namespaceOf(cls.name), cls.name]));
  for (const cls of pageClasses) {
    const natural = namespaceOf(cls.name);
    const alias = curated.aliases.get(cls.name);
    const namespace = alias && (!naturalNamespaces.has(alias) || naturalNamespaces.get(alias) === cls.name)
      ? alias
      : natural;
    const source = fs.readFileSync(cls.file, 'utf8');
    const record = emitLocators(cls, namespace, source, curated, opts, summary);
    const page = emitPageObject(cls, namespace, reserved, opts, summary, record);
    pages.set(cls.name, { className: page.className, importPath: `../../src/pages/drafts/${kebab(namespace)}.page.js`, methods: page.methods });
    summary.pages.push(record);
  }

  const glueVars = new Map<string, Map<string, string>>();
  for (const cls of inventory.classes.filter((c) => c.kind === 'steps')) {
    const source = fs.readFileSync(cls.file, 'utf8');
    const vars = new Map<string, string>();
    for (const m of source.matchAll(/(?:^|\s)([A-Z]\w*(?:Page|Component))\s+(\w+)\s*(?:=|;)/g)) vars.set(m[2]!, m[1]!);
    glueVars.set(cls.name, vars);
  }

  const ctx: SpecContext = { definitions: inventory.stepDefinitions, glueVars, pages, used: new Set(), unbound: summary.unbound };
  for (const feature of [...inventory.features].sort((a, b) => a.relativeFile.localeCompare(b.relativeFile))) {
    summary.features.push(emitFeatureDraft(feature, ctx, curated, opts, summary));
  }

  writeFile(path.join(opts.rootDir, 'docs', 'migration-drafts-report.md'), renderDraftReport(summary, opts), opts, summary);
  return summary;
}

export function renderDraftReport(s: DraftSummary, opts: DraftOptions): string {
  const sum = (f: (x: DraftSummary['features'][number]) => number): number => s.features.reduce((a, x) => a + f(x), 0);
  const psum = (f: (x: DraftSummary['pages'][number]) => number): number => s.pages.reduce((a, x) => a + f(x), 0);
  const scenarios = sum((f) => f.scenarios);
  const drafted = sum((f) => f.drafted);
  const migrated = sum((f) => f.alreadyMigrated.length);
  const lines = [
    '# Migration drafts report',
    '',
    `Generated by \`npm run migrate:drafts\` from **${opts.sourceLabel}**. Regenerated on every run — do not edit.`,
    'Workflow and rules: `.claude/skills/aiqa-ksp-migration/SKILL.md`. Status of finished modules: `docs/migration-tracker.md`.',
    '',
    '## Totals',
    '',
    '| | Count |',
    '| --- | --- |',
    `| Feature files | ${s.features.length} |`,
    `| Scenarios / Examples rows | ${scenarios} |`,
    `| Already migrated (curated spec in tests/e2e) | ${migrated} |`,
    `| Drafted as \`test.fixme\` in tests/drafts | ${drafted} |`,
    `| Draft steps still TODO | ${sum((f) => f.todoSteps)} |`,
    `| Draft steps with no step definition | ${sum((f) => f.unboundSteps)} |`,
    `| Page objects | ${s.pages.length} |`,
    `| Locators added (new files + blocks in curated files) | ${psum((p) => p.added)} |`,
    `| Locator keys kept from curated files | ${psum((p) => p.keptCurated.length)} |`,
    `| Locator keys whose Selenium selector differs from the curated one | ${psum((p) => p.conflicts.length)} |`,
    `| Parameterised (\`By fn(String)\`) locators, listed as YAML comments | ${psum((p) => p.dynamic)} |`,
    `| Page methods translated cleanly / throwing TODO | ${psum((p) => p.cleanMethods)} / ${psum((p) => p.todoMethods)} |`,
    '',
    '## Features',
    '',
    '| Feature file | Draft spec | Rows | Drafted | Already migrated | TODO steps | Unbound |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...s.features.map(
      (f) =>
        `| \`${f.file}\` | ${f.spec ? `\`${f.spec}\`` : '—'} | ${f.scenarios} | ${f.drafted} | ${f.alreadyMigrated.length} | ${f.todoSteps} | ${f.unboundSteps} |`,
    ),
    '',
    '## Page objects and locators',
    '',
    '| Selenium class | Namespace | Locator file | Added | Kept curated | Differs from curated | Dynamic | Methods clean / TODO |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...s.pages.map(
      (p) =>
        `| ${p.className} | \`${p.namespace}\`${p.curated ? ' (curated)' : ''} | \`${p.locatorFile}\` | ${p.added} | ${p.keptCurated.length} | ${p.conflicts.length ? p.conflicts.map((c) => `\`${c}\``).join(', ') : '0'} | ${p.dynamic} | ${p.cleanMethods} / ${p.todoMethods} |`,
    ),
    '',
    '"Differs from curated": the curated YAML already declares that key with another selector. The curated one is kept',
    '(it was verified on STG); compare the two only if that element fails.',
    '',
    '## Roles without a Playwright project',
    '',
    'Draft tests for these roles match no project and cannot run until the role is added to',
    '`config/environments.ts` (credential keys: `docs/migration-framework-map.md`).',
    '',
    ...(s.missingRoles.size
      ? ['| Role | Draft tests |', '| --- | --- |', ...[...s.missingRoles].sort((a, b) => b[1] - a[1]).map(([r, n]) => `| ${r} | ${n} |`)]
      : ['None.']),
    '',
    '## Most frequent unbound steps',
    '',
    ...(s.unbound.size
      ? [
          '| Gherkin step | Uses |',
          '| --- | --- |',
          ...[...s.unbound]
            .sort((a, b) => b[1] - a[1])
            .slice(0, 40)
            .map(([t, n]) => `| ${t.replace(/\|/g, '\\|')} | ${n} |`),
        ]
      : ['None.']),
    '',
  ];
  return lines.join('\n');
}

export const DRAFT_MARKER = 'DRAFT(migration)';
const BLOCK_START = `# >>> ${DRAFT_MARKER}: generated locators, not yet verified — regenerated by \`npm run migrate:drafts\``;
const BLOCK_END = `# <<< ${DRAFT_MARKER}`;

export interface DraftOptions {
  /** Selenium source root (the folder holding `pages/`, `scenarios/`, ...). */
  input: string;
  /** Framework root. */
  rootDir: string;
  /** Human label for the source, e.g. `ksp-test-automation@main 36caeed`. */
  sourceLabel: string;
  /** Roles that have a Playwright project (`Object.keys(env.users)`). */
  knownRoles: string[];
  dryRun?: boolean;
}

export interface DraftSummary {
  features: Array<{
    file: string;
    spec?: string;
    scenarios: number;
    drafted: number;
    alreadyMigrated: string[];
    todoSteps: number;
    unboundSteps: number;
  }>;
  pages: Array<{
    className: string;
    namespace: string;
    locatorFile: string;
    curated: boolean;
    added: number;
    keptCurated: string[];
    conflicts: string[];
    dynamic: number;
    page: string;
    cleanMethods: number;
    todoMethods: number;
  }>;
  missingRoles: Map<string, number>;
  unbound: Map<string, number>;
  written: string[];
}

/* ------------------------------------------------------------- helpers */

const kebab = (s: string): string =>
  s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[_\s]+/g, '-').toLowerCase();
const pascal = (s: string): string => s.charAt(0).toUpperCase() + s.slice(1);
const camel = (s: string): string => s.charAt(0).toLowerCase() + s.slice(1);
const q = (s: string): string => JSON.stringify(s);
const escapeRe = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const BLOCK_RE = new RegExp(`\\n?${escapeRe(BLOCK_START)}[\\s\\S]*?${escapeRe(BLOCK_END)}\\n?`);

/** A whole file this module owns: the marker is on its first lines, not inside a merged block. */
const isDraftFile = (text: string): boolean => text.split('\n', 2).join('\n').includes(DRAFT_MARKER);

/** A value that is valid TypeScript on its own: a literal, or a known name. */
function isSafeArg(arg: string, names: Set<string>): boolean {
  const a = arg.trim();
  return (
    /^'(?:[^'\\]|\\.)*'$/.test(a) ||
    /^-?(0|[1-9]\d*)(\.\d+)?$/.test(a) ||
    /^(true|false)$/.test(a) ||
    names.has(a)
  );
}

function tsType(javaType: string): string {
  const t = javaType.replace(/final\s+/, '').trim();
  if (/^(int|long|short|byte|double|float|Integer|Long|Double|Float)$/.test(t)) return 'number';
  if (/^(boolean|Boolean)$/.test(t)) return 'boolean';
  if (/^(String|CharSequence)$/.test(t)) return 'string';
  if (/^(List|ArrayList)<\s*String\s*>$/.test(t)) return 'string[]';
  if (/^(List|ArrayList)<\s*Integer\s*>$/.test(t)) return 'number[]';
  if (t === 'void') return 'void';
  return 'unknown';
}

/** Coerce a Gherkin-captured literal to what the page method expects. */
function coerce(arg: string, type: string): string {
  if (type === 'string' && /^-?\d+(\.\d+)?$|^(true|false)$/.test(arg.trim())) return `'${arg.trim()}'`;
  return arg;
}

function writeFile(file: string, content: string, opts: DraftOptions, summary: DraftSummary): void {
  summary.written.push(path.relative(opts.rootDir, file));
  if (opts.dryRun) return;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

/** Remove previously generated drafts so renamed/removed sources leave nothing behind. */
function clearDrafts(dir: string, suffix: string, opts: DraftOptions): void {
  if (opts.dryRun || !fs.existsSync(dir)) return;
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    if (name.endsWith(suffix) && isDraftFile(fs.readFileSync(full, 'utf8'))) fs.unlinkSync(full);
  }
}

/* ----------------------------------------------------- curated context */

interface Curated {
  /** namespace → locator file, for files not generated by this module. */
  locatorFiles: Map<string, string>;
  /** Java class name → curated namespace, from `Migrated from Selenium X.java`. */
  aliases: Map<string, string>;
  /** Every test ID mentioned in a curated spec, and where. */
  ids: Map<string, string>;
}

function readCurated(rootDir: string): Curated {
  const locatorFiles = new Map<string, string>();
  const aliases = new Map<string, string>();
  const locatorsDir = path.join(rootDir, 'locators');
  for (const name of fs.readdirSync(locatorsDir).filter((n) => n.endsWith('.locators.yml'))) {
    const file = path.join(locatorsDir, name);
    const text = fs.readFileSync(file, 'utf8');
    if (isDraftFile(text)) continue;
    const ns = (YAML.parse(text.replace(BLOCK_RE, '\n')) as { meta?: { name?: string } })?.meta?.name;
    if (!ns) continue;
    locatorFiles.set(ns, file);
    // The header names the Selenium page the curated file was migrated from.
    const origin = /\b([A-Z]\w+(?:Page|Component))\.java\b/.exec(text.replace(BLOCK_RE, '\n'));
    if (origin && !aliases.has(origin[1]!)) aliases.set(origin[1]!, ns);
  }

  const ids = new Map<string, string>();
  const e2e = path.join(rootDir, 'tests', 'e2e');
  for (const name of fs.existsSync(e2e) ? fs.readdirSync(e2e) : []) {
    if (!name.endsWith('.spec.ts')) continue;
    const text = fs.readFileSync(path.join(e2e, name), 'utf8');
    for (const m of text.matchAll(/\b([A-Z]{2,6}[-_]\d+)\b/g)) if (!ids.has(m[1]!)) ids.set(m[1]!, `tests/e2e/${name}`);
  }
  return { locatorFiles, aliases, ids };
}

/* ------------------------------------------------------------ locators */

interface DynamicLocator {
  name: string;
  params: string;
  how: string;
  template: string;
}

/** `By linkLocator(String name) { return By.xpath("//a[.='" + name + "']"); }` */
function dynamicLocators(source: string): DynamicLocator[] {
  const out: DynamicLocator[] = [];
  const re = /\bBy\s+(\w+)\s*\(([^)]*)\)\s*\{\s*return\s+By\s*\.\s*(\w+)\s*\(([\s\S]*?)\)\s*;\s*\}/g;
  for (const m of source.matchAll(re)) {
    const template = m[4]!
      .split(/\s*\+\s*/)
      .map((part) => {
        const lit = /^"((?:[^"\\]|\\.)*)"$/.exec(part.trim());
        return lit ? lit[1]!.replace(/\\"/g, '"') : `{${part.trim()}}`;
      })
      .join('');
    out.push({ name: m[1]!, params: m[2]!.trim(), how: m[3]!, template });
  }
  return out;
}

/** Selenium locator → a house-style YAML element body. The Selenium selector stays primary. */
function elementBody(locator: SeleniumLocator): Record<string, unknown> {
  switch (locator.how) {
    case 'xpath':
      return { xpath: locator.value };
    case 'css':
      return { css: locator.value };
    case 'id':
      return { css: `#${locator.value}` };
    case 'name':
      return { css: `[name="${locator.value.replace(/"/g, '\\"')}"]` };
    case 'className':
      return { css: locator.value.trim().split(/\s+/).map((c) => `.${c}`).join('') };
    case 'tagName':
      return { css: locator.value };
    default: {
      const step = mapLocator(locator).steps[0]!;
      return { role: step.role, name: step.name, ...(step.exact === false ? { exact: false } : {}) };
    }
  }
}

function describeElement(field: { name: string; comment?: string }, pageTitle: string): string {
  if (field.comment) return field.comment.replace(/\s+/g, ' ').trim();
  return `${humanise(field.name)} on the ${pageTitle} page`;
}

function emitLocators(
  cls: JavaClass,
  namespace: string,
  source: string,
  curated: Curated,
  opts: DraftOptions,
  summary: DraftSummary,
): DraftSummary['pages'][number] {
  const pageTitle = humanise(namespaceOf(cls.name));
  const curatedFile = curated.locatorFiles.get(namespace);
  const existing = new Map<string, unknown>();
  let curatedText = '';
  if (curatedFile) {
    curatedText = fs.readFileSync(curatedFile, 'utf8').replace(BLOCK_RE, '\n');
    const parsed = YAML.parse(curatedText) as { elements?: Record<string, unknown> };
    for (const [k, v] of Object.entries(parsed?.elements ?? {})) existing.set(k, v);
  }

  const elements: Record<string, Record<string, unknown>> = {};
  const keptCurated: string[] = [];
  const conflicts: string[] = [];
  for (const field of cls.fields) {
    const body = elementBody(field.locator);
    if (existing.has(field.name)) {
      const cur = existing.get(field.name) as Record<string, unknown> | string;
      const curSelector = typeof cur === 'string' ? cur : (cur.xpath ?? cur.css ?? cur.selector);
      const mine = body.xpath ?? body.css;
      if (mine && curSelector && String(curSelector) !== String(mine) && !String(curSelector).includes(String(mine))) {
        conflicts.push(field.name);
      } else keptCurated.push(field.name);
      continue;
    }
    elements[field.name] = {
      description: describeElement(field, pageTitle),
      ...body,
      ...(field.isList ? { multiple: true } : {}),
      tags: ['draft'],
    };
  }

  const dynamic = dynamicLocators(source);
  const dynamicComment = dynamic.length
    ? [
        '',
        `# Parameterised locators in ${cls.name} — build these in the page object`,
        '# (e.g. a base key plus `.filter({ hasText })`), they cannot be static keys:',
        ...dynamic.map((d) => `#   ${d.name}(${d.params}) -> ${d.how}: ${d.template.replace(/\n/g, ' ')}`),
      ]
    : [];

  const added = Object.keys(elements).length;
  const rendered = added ? YAML.stringify({ elements }, { lineWidth: 0 }).replace(/^elements:\n/, '') : '';

  let locatorFile: string;
  if (curatedFile) {
    locatorFile = curatedFile;
    const block = added || dynamic.length
      ? [
          BLOCK_START,
          `# Source: ${opts.sourceLabel} — ${cls.relativeFile}. Keys already declared above were kept as they are.`,
          rendered.trimEnd(),
          ...dynamicComment,
          BLOCK_END,
          '',
        ].join('\n')
      : '';
    // Curated bytes are kept exactly; only the appended block takes the
    // file's line ending (the repository has CRLF and mixed files).
    const eol = curatedText.includes('\r\n') ? '\r\n' : '\n';
    const body = curatedText.replace(/\s+$/, '');
    const next = block ? `${body}${eol}${eol}${block.replace(/\n/g, eol)}` : `${body}${eol}`;
    if (next !== fs.readFileSync(curatedFile, 'utf8')) writeFile(curatedFile, next, opts, summary);
  } else {
    locatorFile = path.join(opts.rootDir, 'locators', `${namespace}.locators.yml`);
    const content = [
      `# ${DRAFT_MARKER} — generated by \`npm run migrate:drafts\`; regenerated on every run.`,
      `# Source: ${opts.sourceLabel} — ${cls.relativeFile}.`,
      '# Selectors are the Selenium originals, NOT yet verified on STG. To curate:',
      '# remove the first line (the generator then stops rewriting this file),',
      '# verify each key on STG, sharpen descriptions, drop the `draft` tag.',
      '',
      YAML.stringify(
        { meta: { name: namespace, description: `${pageTitle} page — migrated from Selenium ${cls.name}.java` } },
        { lineWidth: 0 },
      ).trimEnd(),
      '',
      ...(added ? ['elements:', rendered.trimEnd()] : ['elements: {}']),
      ...dynamicComment,
      '',
    ].join('\n');
    writeFile(locatorFile, content, opts, summary);
  }

  return {
    className: cls.name,
    namespace,
    locatorFile: path.relative(opts.rootDir, locatorFile),
    curated: Boolean(curatedFile),
    added,
    keptCurated,
    conflicts,
    dynamic: dynamic.length,
    page: '',
    cleanMethods: 0,
    todoMethods: 0,
  };
}


/**
 * Draft generation: a whole Selenium/Cucumber suite → framework-shaped drafts
 * that are safe to keep in the repository while the migration is in progress.
 *
 * `aiqa migrate` produces a review copy in `migration/output/`. This produces
 * the in-repo working set the team migrates *from*, module by module:
 *
 *   locators/<ns>.locators.yml      every element of every page object. A
 *                                   curated file is never rewritten: missing
 *                                   keys are appended inside a marked block.
 *   src/pages/drafts/<ns>.page.ts   page objects. A method that did not
 *                                   translate cleanly throws, so a draft can
 *                                   never pass by silently doing nothing.
 *   tests/drafts/<feature>.spec.ts  one test per scenario / Examples row, all
 *                                   `test.fixme` — listed, reported, never run.
 *   docs/migration-drafts-report.md the work list.
 *
 * Re-running is safe: only files carrying DRAFT_MARKER (and the marked block in
 * curated YAML) are regenerated. Scenarios whose test ID already appears in a
 * curated spec under tests/e2e/ are left out, so a migrated test is never
 * duplicated by its draft.
 */
